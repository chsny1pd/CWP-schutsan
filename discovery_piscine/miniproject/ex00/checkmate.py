def checkmate(board: str):
    try:
        # --- ขั้นตอนที่ 1: เตรียมข้อมูลกระดาน ---
        # นำข้อความกระดานมาแยกเป็นบรรทัดๆ ด้วยคำสั่ง split('\n') 
        # และใช้ List Comprehension กรองบรรทัดที่ว่างเปล่า (Empty string) ทิ้งไป เพื่อป้องกันบั๊ก
        rows = [row for row in board.split('\n') if row]
        
        # ถ้าไม่มีข้อมูลในกระดานเลย (เช่น ส่งค่าว่างมา) ให้หยุดการทำงาน
        if not rows:
            return

        size = len(rows)  # หาขนาดความสูงของกระดาน (มีกี่บรรทัด)
        king_pos = None   # ตัวแปรเก็บพิกัดของ King ในรูปแบบ (แถว, คอลัมน์)
        king_count = 0    # ตัวแปรนับจำนวน King บนกระดาน

        # --- ขั้นตอนที่ 2: ตรวจสอบกฎของกระดานและหาพิกัด King ---
        for r in range(size):
            # กติกา: กระดานต้องเป็นสี่เหลี่ยมจัตุรัส (ความกว้างต้องเท่ากับความสูงเสมอ)
            if len(rows[r]) != size:
                print("Error")
                return
            
            # กวาดสายตาหาตัว 'K' ในแต่ละคอลัมน์ของบรรทัดนี้
            for c in range(size):
                if rows[r][c] == 'K':
                    king_pos = (r, c)  # บันทึกพิกัด (แถวที่ r, ช่องที่ c)
                    king_count += 1    # นับว่าเจอ King แล้ว 1 ตัว

        # กติกา: บนกระดานจะต้องมี King เพียงตัวเดียวเท่านั้น ถ้ามีเกินหรือไม่มีเลยให้ฟ้อง Error
        if king_count != 1:
            print("Error")
            return

        # ดึงพิกัดแถว (kr) และคอลัมน์ (kc) ของ King ออกมาเพื่อใช้เป็นจุดศูนย์กลางเรดาร์
        kr, kc = king_pos

        # --- ขั้นตอนที่ 3: กำหนดทิศทางของเรดาร์ทั้ง 8 ทิศ ---
        # รูปแบบเวกเตอร์: (ขยับแถวทีละเท่าไหร่, ขยับคอลัมน์ทีละเท่าไหร่, [รายชื่อหมากที่อันตรายในทิศนี้])
        directions = [
            (-1, 0, ['R', 'Q']),        # ทิศขึ้น: ขยับแถวขึ้น (-1) | ระวัง Rook, Queen
            (1, 0, ['R', 'Q']),         # ทิศลง: ขยับแถวลง (+1) | ระวัง Rook, Queen
            (0, -1, ['R', 'Q']),        # ทิศซ้าย: ขยับคอลัมน์ซ้าย (-1) | ระวัง Rook, Queen
            (0, 1, ['R', 'Q']),         # ทิศขวา: ขยับคอลัมน์ขวา (+1) | ระวัง Rook, Queen
            (-1, -1, ['B', 'Q']),       # ทิศเฉียงซ้ายบน | ระวัง Bishop, Queen
            (-1, 1, ['B', 'Q']),        # ทิศเฉียงขวาบน | ระวัง Bishop, Queen
            (1, -1, ['B', 'Q', 'P']),   # ทิศเฉียงซ้ายล่าง | ระวัง Bishop, Queen และ Pawn
            (1, 1, ['B', 'Q', 'P'])     # ทิศเฉียงขวาล่าง | ระวัง Bishop, Queen และ Pawn
        ]
        # เหตุผลที่ Pawn อยู่แค่เฉียงล่าง: เพราะ Pawn ฝั่งศัตรูต้องอยู่ต่ำกว่าเรา ถึงจะโจมตีเฉียงขึ้นมาหาเราได้

        # --- ขั้นตอนที่ 4: เริ่มยิงเรดาร์สแกนออกไปทีละทิศ ---
        for dr, dc, threats in directions:
            # เริ่มสแกนจากช่องที่ติดกับ King ไป 1 ก้าว ตามทิศทางเวกเตอร์ปัจจุบัน
            r = kr + dr
            c = kc + dc
            distance = 1  # ตัวแปรกำหนดระยะห่างจาก King (เริ่มที่ 1 ช่อง)
            
            # สแกนตรงไปเรื่อยๆ ตราบใดที่สายตายังไม่ทะลุขอบกระดาน (พิกัดต้องอยู่ระหว่าง 0 ถึง size-1)
            while 0 <= r < size and 0 <= c < size:
                piece = rows[r][c]  # อ่านค่าว่าช่องที่สแกนอยู่เป็นตัวอักษรอะไร
                
                # ถ้าเจอหมากตัวใดตัวหนึ่งขวางหน้า (ที่ไม่ใช่ช่องว่าง '.')
                if piece in ['P', 'B', 'R', 'Q']:
                    
                    # ตรวจสอบว่าหมากตัวนั้นมีรูปแบบการโจมตีตรงกับทิศทางนี้หรือไม่
                    if piece in threats:
                        
                        # กติกาพิเศษ: Pawn เป็นหมากระยะประชิด โจมตีได้แค่ระยะ 1 ช่องเท่านั้น
                        # ถ้าระยะห่าง (distance) มากกว่า 1 แปลว่ามันแทงไม่ถึง ให้ถือว่ามันเป็นแค่สิ่งกีดขวาง
                        if piece == 'P' and distance > 1:
                            break 
                            
                        # ถ้าผ่านเงื่อนไขมาได้ทั้งหมด แปลว่า King กำลังถูกเล็ง!
                        print("Success")
                        return
                    
                    # ถ้าเจอหมากขวางหน้า แต่ไม่ใช่หมากที่โจมตีในทิศนี้ได้ (เช่น มองตรงไปเจอ Bishop)
                    # หมากตัวนี้จะทำหน้าที่เป็น "กำแพง" บังการโจมตีจากหมากตัวอื่นที่อยู่ด้านหลังมันทันที
                    break  # สั่ง break เพื่อหยุดสแกนทิศนี้ แล้วข้ามไปสแกนทิศต่อไป
                
                # ถ้าช่องปัจจุบันยังเป็นแค่ช่องว่าง ให้ขยับสายตามองไกลออกไปอีก 1 ก้าวในทิศทางเดิม
                r += dr
                c += dc
                distance += 1  # เพิ่มตัวนับระยะห่างออกไปอีก 1 ช่อง

        # หากเรดาร์สแกนครบทั้ง 8 ทิศทางแล้วไม่พบอันตรายเลย แปลว่า King ปลอดภัยดี
        print("Fail")
        
    except Exception:
        # ดักจับ Error ขั้นสุดท้าย หากมีข้อผิดพลาดที่ไม่คาดคิด โปรแกรมจะไม่แครช แต่จะพิมพ์ Error ตามกติกา
        print("Error")